        public void PlayVideo(H3BatchUpscaleItem? item)
        {
            if (item == null) return;
            ActivePreviewUri = item.VideoPath;
            ActivePreviewLabel = item.FileName;
        }

        public void ToggleVideo(H3BatchUpscaleItem? item)
        {
            if (item != null)
                item.IsSelected = !item.IsSelected;
        }

        public void PlayUpscaled(H3BatchUpscaleItem? item)
        {
            if (item?.HasUpscale == true)
            {
                ActivePreviewUri = item.UpscaledPath;
                ActivePreviewLabel = $"{item.FileName} (upscaled)";
            }
        }

        public void RevealVideo(H3BatchUpscaleItem? item)
        {
            if (item == null) return;
            try
            {
                var path = item.HasUpscale ? item.UpscaledPath! : item.VideoPath;
                System.Diagnostics.Process.Start("explorer.exe", $"/select,\"{path}\"");
            }
            catch (Exception ex) { AddLog($"Could not reveal: {ex.Message}"); }
        }
