        public async Task ScanAsync()
        {
            if (IsScanning || IsUpscaling) return;
            var folder = ScanFolder;

            IsScanning = true;
            ScanStatus = "Scanning...";

            try
            {
                var (exists, found) = await Task.Run(() =>
                {
                    if (string.IsNullOrWhiteSpace(folder) || !Directory.Exists(folder))
                        return (false, new List<H3BatchUpscaleItem>());
                    var items = ReadFolder(folder);

                    // Check for already upscaled videos
                    var outDir = OutputDirectory();
                    if (Directory.Exists(outDir))
                    {
                        foreach (var item in items)
                        {
                            var candidate = Path.Combine(outDir, Path.GetFileName(item.VideoPath));
                            if (File.Exists(candidate)) item.UpscaledPath = candidate;
                        }
                    }
                    return (true, items);
                });

                FolderExists = exists;
                OnPropertyChanged(nameof(HasScanFolder));
                OpenScanFolderCommand.NotifyCanExecuteChanged();

                if (!exists)
                {
                    _all.Clear();
                    Items.Clear();
                    ScanStatus = string.IsNullOrWhiteSpace(folder)
                        ? "Choose a folder containing H3 preview videos."
                        : $"Folder does not exist: {folder}";
                    RefreshCounts();
                    return;
                }

                Application.Current.Dispatcher.Invoke(() =>
                {
                    var previous = _all.ToDictionary(i => i.Key, i => i);
                    _all.Clear();
                    foreach (var item in found)
                    {
                        if (previous.TryGetValue(item.Key, out var old))
                        {
                            item.IsSelected = old.IsSelected;
                            item.Thumbnail = old.Thumbnail;
                            item.Status = old.Status;
                        }
                        item.PropertyChanged += ItemPropertyChanged;
                        _all.Add(item);
                    }
                    ApplyFilter();
                    ScanStatus = _all.Count == 0
                        ? "No MP4 videos found here."
                        : $"{_all.Count} video(s) found.";
                });

                await FillThumbnailsAsync();
            }
            catch (Exception ex)
            {
                AddLog($"Scan failed: {ex.Message}");
                ScanStatus = $"Scan failed: {ex.Message}";
            }
            finally { IsScanning = false; }
        }

        private List<H3BatchUpscaleItem> ReadFolder(string folder)
        {
            var option = IncludeSubfolders ? SearchOption.AllDirectories : SearchOption.TopDirectoryOnly;
            var videos = Directory.EnumerateFiles(folder, "*.mp4", option)
                                  .Where(f => !Path.GetFileName(f).StartsWith("upscale_", StringComparison.OrdinalIgnoreCase))
                                  .ToList();

            var items = new List<H3BatchUpscaleItem>();
            foreach (var video in videos)
            {
                items.Add(new H3BatchUpscaleItem(this, video));
            }

            return items.OrderByDescending(i => new FileInfo(i.VideoPath).CreationTime).ToList();
        }

        private void ItemPropertyChanged(object? sender, System.ComponentModel.PropertyChangedEventArgs e)
        {
            if (e.PropertyName == nameof(H3BatchUpscaleItem.IsSelected)) RefreshCounts();
        }

        private void ApplyFilter()
        {
            var needle = FilterText.Trim();
            IEnumerable<H3BatchUpscaleItem> query = _all;
            if (needle.Length > 0)
                query = query.Where(i => i.SearchText.Contains(needle, StringComparison.OrdinalIgnoreCase));
            if (HideAlreadyUpscaled)
                query = query.Where(i => !i.HasUpscale);

            var filtered = query.ToList();
            Items.Clear();
            foreach (var item in filtered)
                Items.Add(item);
            RefreshCounts();
        }

