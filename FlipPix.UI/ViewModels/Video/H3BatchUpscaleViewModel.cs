        private async Task FillThumbnailsAsync()
        {
            string? ffmpegPath = null;

            foreach (var item in _all.ToList())
            {
                if (item.Thumbnail != null) continue;

                BitmapImage? bmp = null;

                // First try to find existing thumbnail
                var thumbPath = FindExistingThumbnail(item.VideoPath);
                if (thumbPath != null)
                {
                    bmp = await Task.Run(() => LoadThumbnail(thumbPath));
                }

                // Fallback to FFmpeg extraction
                if (bmp == null)
                {
                    ffmpegPath ??= FindFFmpeg();
                    if (ffmpegPath != null)
                    {
                        bmp = await Task.Run(() => ExtractThumbnailWithFFmpeg(item.VideoPath, ffmpegPath));
                    }
                }

                if (bmp != null)
                {
                    Application.Current?.Dispatcher.Invoke(() => item.Thumbnail = bmp);
                }
            }
        }

        private BitmapImage? LoadThumbnail(string path)
        {
            try
            {
                var bmp = new BitmapImage();
                bmp.BeginInit();
                bmp.CacheOption = BitmapCacheOption.OnLoad;
                bmp.UriSource = new Uri(path, UriKind.Absolute);
                bmp.DecodePixelWidth = 160;
                bmp.EndInit();
                bmp.Freeze();
                return bmp;
            }
            catch { return null; }
        }

        private BitmapImage? ExtractThumbnailWithFFmpeg(string videoPath, string ffmpegPath)
        {
            try
            {
                var outPath = Path.Combine(Path.GetTempPath(), $"h3batch_thumb_{Guid.NewGuid():N}.png");
                var psi = new System.Diagnostics.ProcessStartInfo
                {
                    FileName = ffmpegPath,
                    Arguments = $"-y -i \"{videoPath}\" -frames:v 1 -q:v 3 \"{outPath}\"",
                    UseShellExecute = false,
                    RedirectStandardError = true,
                    CreateNoWindow = true
                };

                using (var p = System.Diagnostics.Process.Start(psi))
                {
                    if (p == null) return null;
                    p.StandardError.ReadToEnd();
                    p.WaitForExit(10000);
                }

                if (!File.Exists(outPath) || new FileInfo(outPath).Length == 0) return null;

                var bmp = LoadThumbnail(outPath);
                try { File.Delete(outPath); } catch { }
                return bmp;
            }
            catch { return null; }
        }

        /// <summary>
        /// Finds an existing thumbnail for a video file.
        /// H3 Video Editor generates thumbnails like: clip_00001_thumb_00001_.png
        /// Video files are named like: clip_00001_00001_.mp4 (clip_{index}_{render}_.mp4)
        /// </summary>
        private string? FindExistingThumbnail(string videoPath)
        {
            try
            {
                var dir = Path.GetDirectoryName(videoPath);
                if (string.IsNullOrEmpty(dir)) return null;

                var videoName = Path.GetFileNameWithoutExtension(videoPath);

                // Extract clip index from video name like "clip_00002_00001_" -> "clip_00002"
                // Pattern: clip_{clipIndex}_{renderIndex}_ -> thumbnail is clip_{clipIndex}_thumb_*
                if (videoName.StartsWith("clip_", StringComparison.OrdinalIgnoreCase))
                {
                    var parts = videoName.Split('_');
                    if (parts.Length >= 2)
                    {
                        var clipPrefix = $"{parts[0]}_{parts[1]}"; // "clip_00002"
                        var thumbs = Directory.GetFiles(dir, $"{clipPrefix}_thumb_*.png");
                        if (thumbs.Length > 0)
                            return thumbs[0];
                    }
                }

                // Try exact match: video.mp4 -> video_thumb_*.png
                var exactThumbs = Directory.GetFiles(dir, $"{videoName}_thumb_*.png");
                if (exactThumbs.Length > 0)
                    return exactThumbs[0];

                // Try any PNG starting with video name
                var candidates = Directory.GetFiles(dir, "*.png")
                    .Where(f => Path.GetFileName(f).StartsWith(videoName, StringComparison.OrdinalIgnoreCase))
                    .ToArray();
                if (candidates.Length > 0)
                    return candidates[0];
            }
            catch { }

            return null;
        }

        private string? FindFFmpeg()
        {
            var candidates = new[]
            {
                @"C:\ffmpeg\bin\ffmpeg.exe",
                @"C:\Program Files\ffmpeg\bin\ffmpeg.exe",
                Path.Combine(Environment.GetFolderPath(Environment.SpecialFolder.ProgramFiles), "ffmpeg", "bin", "ffmpeg.exe"),
                Path.Combine(Environment.GetFolderPath(Environment.SpecialFolder.LocalApplicationData), "ffmpeg", "bin", "ffmpeg.exe"),
            };

            foreach (var path in candidates)
            {
                if (File.Exists(path)) return path;
            }

            // Try PATH
            var pathEnv = Environment.GetEnvironmentVariable("PATH") ?? string.Empty;
            foreach (var dir in pathEnv.Split(Path.PathSeparator))
            {
                try
                {
                    var candidate = Path.Combine(dir, "ffmpeg.exe");
                    if (File.Exists(candidate)) return candidate;
                }
                catch { }
            }

            return null;
        }

