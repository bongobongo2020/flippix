        private async Task<string?> ResolveOutputAsync(string promptId, string saveNodeId, string originalName)
        {
            try
            {
                var byNode = await _comfyUIService.HttpClient.GetOutputsByNodeAsync(promptId, CancellationToken.None);
                if (byNode.TryGetValue(saveNodeId, out var outputs) && outputs.Count > 0)
                {
                    AddLog($"ComfyUI returned output: {outputs[0]}");

                    // Try to find the file locally
                    var settings = _settingsService.Settings;
                    var outputDir = !string.IsNullOrEmpty(settings?.OutputFolderPath)
                        ? Path.Combine(settings.OutputFolderPath, "H3BatchUpscale")
                        : OutputDirectory();

                    if (Directory.Exists(outputDir))
                    {
                        var pattern = Path.GetFileNameWithoutExtension(originalName) + "*";
                        var files = Directory.GetFiles(outputDir, pattern)
                                             .OrderByDescending(f => new FileInfo(f).CreationTime)
                                             .FirstOrDefault();
                        if (files != null) return files;
                    }

                    // Return the ComfyUI output path
                    return outputs[0];
                }
            }
            catch (Exception ex)
            {
                AddLog($"Error resolving output: {ex.Message}");
            }
            return null;
        }

