        private async Task RunUpscaleAsync()
        {
            if (!HasSelection || IsUpscaling) return;

            var selected = Items.Where(i => i.IsSelected && !i.HasUpscale).ToList();
            if (selected.Count == 0)
            {
                AddLog("All selected videos have already been upscaled.");
                return;
            }

            IsUpscaling = true;
            _runCts = new CancellationTokenSource();
            Progress = 0;

            var outDir = OutputDirectory();
            Directory.CreateDirectory(outDir);

            int completed = 0;
            int total = selected.Count;

            try
            {
                using var lease = await _workflowCoordinator.AcquireAsync("h3_batch_upscale", _runCts.Token);

                foreach (var item in selected)
                {
                    if (_runCts.Token.IsCancellationRequested) break;

                    item.IsBusy = true;
                    item.Status = "Upscaling...";
                    ScanStatus = $"Upscaling {completed + 1}/{total}: {item.FileName}";

                    try
                    {
                        // Upload the video
                        AddLog($"Uploading: {item.FileName}");
                        var uploadedName = await _comfyUIService.UploadVideoAsync(item.VideoPath, _runCts.Token);
                        AddLog($"Uploaded as: {uploadedName}");

                        // Build and execute workflow
                        var (workflow, saveNodeId) = BuildUpscaleWorkflow(uploadedName, item.FileName);

                        AddLog($"Submitting upscale workflow ({UpscaleFactor}x)...");
                        var progress = new Progress<FlipPix.ComfyUI.Models.ProgressMessage>(msg =>
                        {
                            if (msg.Data?.Value != null && msg.Data?.Max != null && msg.Data.Max > 0)
                            {
                                var itemProgress = (double)msg.Data.Value / msg.Data.Max * 100;
                                var overallProgress = ((completed + itemProgress / 100) / total) * 100;
                                Progress = overallProgress;
                                item.Status = $"Upscaling: {itemProgress:F0}%";
                            }
                        });

                        var promptId = await _comfyUIService.ExecuteWorkflowAsync(workflow, progress, _runCts.Token);

                        if (!string.IsNullOrEmpty(promptId))
                        {
                            var outputPath = await ResolveOutputAsync(promptId, saveNodeId, item.FileName);
                            if (!string.IsNullOrEmpty(outputPath))
                            {
                                item.UpscaledPath = outputPath;
                                item.Status = "Done";
                                AddLog($"Upscaled: {item.FileName} -> {Path.GetFileName(outputPath)}");
                            }
                            else
                            {
                                item.Status = "Output not found";
                                AddLog($"Warning: {item.FileName} - output path not resolved");
                            }
                        }
                        else
                        {
                            item.Status = "Failed";
                            AddLog($"Error: {item.FileName} - empty prompt ID");
                        }

                        completed++;
                    }
                    catch (Exception ex)
                    {
                        item.Status = $"Error: {ex.Message}";
                        AddLog($"Error upscaling {item.FileName}: {ex.Message}");
                    }
                    finally
                    {
                        item.IsBusy = false;
                    }
                }

                Progress = 100;
                ScanStatus = $"Completed {completed}/{total} upscales.";
                AddLog($"Batch upscale finished: {completed}/{total}");
            }
            catch (OperationCanceledException)
            {
                ScanStatus = "Upscale cancelled.";
                AddLog("Batch upscale cancelled by user.");
            }
            catch (Exception ex)
            {
                ScanStatus = $"Upscale failed: {ex.Message}";
                AddLog($"Batch upscale failed: {ex.Message}");
            }
            finally
            {
                IsUpscaling = false;
                _runCts?.Dispose();
                _runCts = null;
            }
        }

        private void StopRun()
